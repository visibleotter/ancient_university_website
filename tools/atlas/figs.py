import math
PHI = (1 + 5 ** .5) / 2
def f(v): return f'{v:.1f}'
def pt(p): return f'{f(p[0])},{f(p[1])}'
def L(p, q, c='k', d=False, w=''):
    return f'<line x1="{f(p[0])}" y1="{f(p[1])}" x2="{f(q[0])}" y2="{f(q[1])}" class="s {c}{" d" if d else ""}{(" "+w) if w else ""}"/>'
def C(c, r, cls='k', d=False, fill=None):
    fc = f' f{fill}' if fill else ''
    return f'<circle cx="{f(c[0])}" cy="{f(c[1])}" r="{f(r)}" class="s {cls}{" d" if d else ""}{fc}"/>'
def PG(pts, fill=None, cls='k', d=False, close=True):
    tag = 'polygon' if close else 'polyline'
    fc = f' f{fill}' if fill else ''
    st = (' ' + cls) if cls else ' nos'
    return f'<{tag} points="{" ".join(pt(p) for p in pts)}" class="s{st}{fc}{" d" if d else ""}"/>'
def T(p, s, cls='', a='middle', sz=None):
    st = f' style="font-size:{sz}px"' if sz else ''
    return f'<text x="{f(p[0])}" y="{f(p[1])}" text-anchor="{a}" class="t {cls}"{st}>{s}</text>'
def D(p, cls='k'): return f'<circle cx="{f(p[0])}" cy="{f(p[1])}" r="3.2" class="dot {cls}"/>'
def add(p, q, k=1): return (p[0] + k * q[0], p[1] + k * q[1])
def sub(p, q): return (p[0] - q[0], p[1] - q[1])
def pol(c, r, deg): return (c[0] + r * math.cos(math.radians(deg)), c[1] + r * math.sin(math.radians(deg)))
def unit(v):
    n = math.hypot(*v); return (v[0] / n, v[1] / n)
def ang(v): return math.atan2(v[1], v[0])
def wedge(V, A, B, r=18, c='r', fill=True):
    a1, a2 = ang(sub(A, V)), ang(sub(B, V))
    dl = (a2 - a1 + math.pi) % (2 * math.pi) - math.pi
    pts = [(V[0] + r * math.cos(a1 + dl * i / 16), V[1] + r * math.sin(a1 + dl * i / 16)) for i in range(17)]
    if fill: return PG([V] + pts, fill=c, cls=c)
    return PG(pts, cls=c, close=False)
def right(V, A, B, s=11, c='k'):
    u, w = unit(sub(A, V)), unit(sub(B, V))
    return PG([add(V, u, s), add(add(V, u, s), w, s), add(V, w, s)], cls=c, close=False)
def arcpts(c, r, a0, a1, n=48):
    return [pol(c, r, a0 + (a1 - a0) * i / n) for i in range(n + 1)]
def ARC(c, r, a0, a1, cls='k', d=False):
    return PG(arcpts(c, r, a0, a1), cls=cls, d=d, close=False)
def semicircle(P, Q, away, n=48):
    M = ((P[0] + Q[0]) / 2, (P[1] + Q[1]) / 2); r = math.hypot(*sub(P, M)); a0 = math.degrees(ang(sub(P, M)))
    best = None
    for s in (1, -1):
        mid = pol(M, r, a0 + s * 90); dd = math.hypot(*sub(mid, away))
        if best is None or dd > best[0]: best = (dd, s)
    return arcpts(M, r, a0, a0 + best[1] * 180, n)
def svg(vb, body, label):
    return f'<svg viewBox="{vb}" role="img" aria-label="{label}">' + ''.join(body) + '</svg>'

FIGS = []
def fig(sec, title, ref, cap, vb, body):
    FIGS.append(dict(n=len(FIGS) + 1, sec=sec, title=title, ref=ref, cap=cap, svg=svg(vb, body, title)))

